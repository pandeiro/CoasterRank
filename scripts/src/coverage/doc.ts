import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { COVERAGE_DIR, loadJson } from './lib.js'
import type { SweepOutput } from './sweep.js'

interface Enrichment {
  note: string
  items: Record<string, { facts: string[]; sources: string[] }>
}

function main(): void {
  const sweep = JSON.parse(readFileSync(join(COVERAGE_DIR, 'sweep.json'), 'utf-8')) as SweepOutput
  const enrichment = loadJson<Enrichment>('enrichment.json', { note: '', items: {} })
  const decisions = loadJson<{
    items: { id: string; decided: boolean; crafted?: boolean; supersededBy?: string }[]
  }>('decisions.json', { items: [] })
  const dmap = new Map(decisions.items.map((i) => [i.id, i]))
  const date = sweep.generatedAt.slice(0, 10)
  const lines: string[] = []

  /** Checkbox mirrors decisions.json state; this document is never an applier input. */
  const mark = (id: string): string => {
    const d = dmap.get(id)
    if (!d) return '- [ ]'
    if (d.decided) return '- [x] **✅ decided** —'
    if (d.crafted) return '- [ ] **crafted — review & flip `decided`** —'
    return '- [ ]'
  }
  const superseded = (id: string): string | null => dmap.get(id)?.supersededBy ?? null

  const enrich = (id: string, out: string[]): void => {
    const e = enrichment.items[id]
    if (!e) return
    out.push('  - **Context (agent-researched, verify before deciding):**')
    for (const f of e.facts) out.push(`    - ${f}`)
    for (const s of e.sources) out.push(`    - Source: ${s}`)
  }

  lines.push(`# Data-Readiness Sweep — ${date}`)
  lines.push('')
  lines.push(
    '> **Read-only review doc.** Nothing here has been executed. Each item carries its evidence and a',
  )
  lines.push(
    '> recommended action with a confidence tier. Items tagged **Context** carry agent-researched facts',
  )
  lines.push('> with sources — treat them as leads, not gospel.')
  lines.push('>')
  lines.push(
    '> **How to decide items** (in `data/coverage/decisions.json` — this document is never an input to',
  )
  lines.push('> the applier, and the checkboxes below just mirror that file):')
  lines.push('>')
  lines.push(
    '> 1. Accept a recommendation → set `"decided": true` (leave action/payload as generated)',
  )
  lines.push(
    '> 2. Accept with tweaks → set `"decided": true` and edit the payload (e.g. `overrides`, `to_park_slug`,',
  )
  lines.push('>    creation `status`/`material`/`opening_year`)')
  lines.push(
    '> 3. `action: "review"` items do nothing even if decided — rewrite them into a real action first,',
  )
  lines.push('>    or leave them for later')
  lines.push(
    '> 4. Items marked _superseded_ are ghosts: another decided item already handles that DB row —',
  )
  lines.push('>    leave them untouched')
  lines.push(
    '> 5. Then: `npm run coverage:apply` (dry-run) → review the printed plan → `-- --apply --yes`',
  )
  lines.push('')
  lines.push(
    `Generated by \`npm run coverage:sweep\` + \`npm run coverage:doc\` at ${sweep.generatedAt}.`,
  )
  lines.push('')

  // ---- baseline ----
  const b = sweep.baseline
  lines.push('## Baseline')
  lines.push('')
  lines.push('| Metric | Value |')
  lines.push('| --- | --- |')
  lines.push(`| Parks | ${b.parks} |`)
  lines.push(
    `| Coasters | ${b.coasters} (${b.openCsvCoasters} open-csv + ${b.adminCoasters} admin/community) |`,
  )
  lines.push(`| Coasters in \`Other (unknown location)\` bucket | ${b.otherParkCoasters} |`)
  lines.push(
    `| Status distribution | ${Object.entries(b.statusDist)
      .map(([k, v]) => `${k}: ${v}`)
      .join(', ')} |`,
  )
  lines.push(
    `| Rated coasters / ranked users | ${b.ratedCoasters} / ${b.rankedUsers} — **cleanup window is open: merges remap zero rides today** |`,
  )
  lines.push(
    `| \`coaster_aliases\` rows | ${b.aliasRows} (board former-names search has no data yet — see Punchlist E) |`,
  )
  lines.push('')

  // ---- orphans ----
  lines.push('## A. Orphaned coasters (Other bucket) — re-home')
  lines.push('')
  lines.push(
    `${sweep.orphans.items.length} coasters sit in \`Other (unknown location)\`. ` +
      `${sweep.orphans.resolvedBySlug} resolve deterministically (original park name embedded in the pre-normalization slug kept in \`external_id\`), ` +
      `${sweep.orphans.resolvedByCsv} resolve via CSV cross-reference, ${sweep.orphans.reviewCount} need identification.`,
  )
  lines.push('')
  for (const i of sweep.orphans.items) {
    const ghost = superseded(i.id)
    lines.push(
      ghost
        ? `### ${i.id} — ${i.title} _(superseded by ${ghost} — inert)_`
        : `### ${i.id} — ${i.title}`,
    )
    lines.push(`**Action:** \`${i.action}\` · **Confidence:** ${i.confidence}`)
    lines.push('')
    for (const ev of i.evidence) lines.push(`- ${ev}`)
    enrich(i.id, lines)
    lines.push('')
    lines.push(`**Recommendation:** ${i.recommendation}`)
    lines.push('')
    lines.push(
      ghost
        ? '_(no decision needed — handled by the superseding item)_'
        : `${mark(i.id)} Decide ${i.id}`,
    )
    lines.push('')
  }

  // ---- coaster dups ----
  lines.push('## B. Duplicate coasters within parks')
  lines.push('')
  lines.push(
    `${sweep.dups.items.length} candidate groups (from ${sweep.dups.groupsExamined} same-park normalized-name collisions). Merges remap \`user_rides\` — trivially zero today.`,
  )
  lines.push('')
  for (const i of sweep.dups.items) {
    const ghost = superseded(i.id)
    lines.push(
      ghost
        ? `### ${i.id} — ${i.title} _(superseded by ${ghost} — inert)_`
        : `### ${i.id} — ${i.title}`,
    )
    lines.push(`**Action:** \`${i.action}\` · **Confidence:** ${i.confidence}`)
    lines.push('')
    for (const ev of i.evidence) lines.push(`- ${ev}`)
    enrich(i.id, lines)
    lines.push('')
    lines.push(`**Recommendation:** ${i.recommendation}`)
    lines.push('')
    lines.push(
      ghost
        ? '_(no decision needed — handled by the superseding item)_'
        : `${mark(i.id)} Decide ${i.id}`,
    )
    lines.push('')
  }

  // ---- park dups ----
  lines.push('## C. Duplicate / misnamed parks')
  lines.push('')
  lines.push(
    `${sweep.parkDups.items.length} candidate groups (normalized-name equality or ≥0.84 trigram similarity). Park merges run **first** in the apply order — coaster re-homes assume canonical parks exist.`,
  )
  lines.push('')
  for (const i of sweep.parkDups.items) {
    const ghost = superseded(i.id)
    lines.push(
      ghost
        ? `### ${i.id} — ${i.title} _(superseded by ${ghost} — inert)_`
        : `### ${i.id} — ${i.title}`,
    )
    lines.push(`**Action:** \`${i.action}\` · **Confidence:** ${i.confidence}`)
    lines.push('')
    for (const ev of i.evidence) lines.push(`- ${ev}`)
    enrich(i.id, lines)
    lines.push('')
    lines.push(`**Recommendation:** ${i.recommendation}`)
    lines.push('')
    lines.push(
      ghost
        ? '_(no decision needed — handled by the superseding item)_'
        : `${mark(i.id)} Decide ${i.id}`,
    )
    lines.push('')
  }

  // ---- missing ----
  lines.push('## D. Missing coasters (external lists vs DB)')
  lines.push('')
  lines.push(
    `Coverage of the committed lists (${sweep.missing.entries} entries: VoteCoasters 2024 top-500 + Golden Tickets 2025 steel/wooden): **${sweep.missing.coveragePct}** exact-or-fuzzy.`,
  )
  lines.push('')
  const byCls = new Map<string, typeof sweep.missing.missItems>()
  for (const m of sweep.missing.missItems) {
    const g = byCls.get(m.cls)
    if (g) g.push(m)
    else byCls.set(m.cls, [m])
  }
  const clsOrder = [
    'park_and_coaster_missing',
    'coaster_missing',
    'found_elsewhere',
    'covered_fuzzy',
  ] as const
  const clsDesc: Record<string, string> = {
    park_and_coaster_missing: 'Park itself unmatched — create park (check aliases first) + coaster',
    coaster_missing: 'Park matched, coaster absent — creation candidates',
    found_elsewhere:
      'Found at a different park than the list says — mis-home or park-name mismatch',
    covered_fuzzy: 'Likely covered under a name variant — possible rename or false match',
  }
  for (const cls of clsOrder) {
    const group = byCls.get(cls) ?? []
    if (!group.length) continue
    lines.push(`### ${cls} — ${group.length}`)
    lines.push(`_${clsDesc[cls]}_`)
    lines.push('')
    for (const m of group) {
      const src = m.entry.source
        .replace('golden-ticket-', 'GT-')
        .replace('votecoasters-2024', 'VC24')
      lines.push(
        `- **${m.id}** [${src} #${m.entry.rank}] \`${m.entry.coaster}\` @ ${m.entry.park} — ${m.note}${m.parkMatch ? ` (park → ${m.parkMatch.name}, ${m.parkMatch.how} ${m.parkMatch.sim.toFixed(2)})` : ''}`,
      )
      const c = sweep.creations.find((x) => x.id === m.id)
      if (c) {
        const p = c.payload as Record<string, unknown>
        lines.push(
          `  - Creation payload (edit in \`decisions.json\`): status \`${p.status}\` · material \`${p.material}\` · year \`${p.opening_year ?? '?'}\`${p.suggested_manufacturer ? ` · maker \`${p.suggested_manufacturer}\`` : ''}${p.park_create ? ' · **park will be created**' : ''}`,
        )
      }
      enrich(m.id, lines)
    }
    lines.push('')
  }

  // ---- notables ----
  if (sweep.notables.candidates.length) {
    lines.push('## E. Recent notables (2025–26) — web-researched')
    lines.push('')
    lines.push(sweep.notables.note)
    lines.push('')
    for (const n of sweep.notables.candidates) {
      const status =
        n.inDb === true
          ? '✅ in DB'
          : n.inDb === 'fuzzy'
            ? `🔍 fuzzy → ${n.matchedTo}`
            : '❌ missing'
      lines.push(`- **${n.name}** @ ${n.park} (${n.year}) — ${status} — ${n.why}`)
      for (const s of n.sources) lines.push(`  - Source: ${s}`)
    }
    lines.push('')
  }

  // ---- aliases ----
  lines.push('## F. Alias backfill (follow-on)')
  lines.push('')
  lines.push(
    '`coaster_aliases` is empty, but the original CSV names (often `Name (Park)` with former/alternate names) are recoverable from `external_id` slugs and the CSV itself. ' +
      'Recommended after A–C: one-time backfill inserting the raw CSV name as an alias wherever it differs from the normalized DB name. This is mechanical and low-risk; propose adding it to the apply step.',
  )
  lines.push('')

  // ---- apply order ----
  lines.push('## Proposed apply order (future step, only after your sign-off)')
  lines.push('')
  lines.push('1. Park merges (C) — canonical parks must exist before anything points at them')
  lines.push('2. Orphan re-homes (A) — including create-park items')
  lines.push(
    '3. Coaster merges (B) — remap `user_rides` (none today), insert loser names as aliases',
  )
  lines.push('4. Missing-coaster creations (D/E) — admin UI or script, your choice')
  lines.push('5. Alias backfill (F)')
  lines.push('6. Recompute rankings + regenerate this baseline')
  lines.push('')

  writeFileSync(join(COVERAGE_DIR, `sweep-${date}.md`), lines.join('\n'))
  console.log(`Wrote data/coverage/sweep-${date}.md (${lines.length} lines)`)
}

main()
